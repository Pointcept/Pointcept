#!/usr/bin/env python3
"""Step 1 — merge Bits2Bites (A) + a Bits2Bites2-style export (B) into one
raw-format dataset that is an *expansion* of A (a merge, not a replacement).

Output layout (the raw Bits2Bites format `prepare_bits2bites.py` consumes):

    <out>/Annotations.csv            Patient,Right Class,Left Class,Anterior Bite,Transversal Bite,Median Lines
    <out>/<N>/lower.stl
    <out>/<N>/upper.stl
    <out>/landmarks/dental_<N:04d>.json    (carried over from A; B gets its own in step 3)
    <out>/photos/<N>/...                    (B intra-oral photos, kept aside for later use)
    <out>/reports/dropped_no_manual.csv    (B scans skipped for lack of a human label)
    <out>/reports/id_mapping.csv           (new id -> source + original folder; SENSITIVE)

Behaviour:
  1. A patients 1..N are copied verbatim (meshes + A's landmarks/) as the first
     N output patients, so the output extends A rather than replacing it.
  2. B patients are appended, sorted by numeric patient id, renumbered
     sequentially after A. Only patients whose `classification.json` carries a
     human ("manual") label are kept; a `manual: null` block means the label was
     auto-generated by the pipeline and never reviewed by an expert, so the scan
     is dropped and logged to reports/dropped_no_manual.csv by its ORIGINAL
     folder name (which may embed the real patient name) so the doctor can
     re-annotate it.
  3. B intra-oral photos are copied to photos/<N>/ (all formats incl .heic).
     They sit in a sibling dir that prepare_bits2bites.py ignores, so the
     training path is unaffected — they are preserved for a future extension.
  4. Landmarks are NOT inferred here (step 3 does that); A's existing landmarks
     are carried over as-is.

De-duplication is a separate step (02_dedup.py) run on this output.

Safe to re-run: refuses to touch an existing --output unless --force (the output
is fully derived from the two sources, so regenerating is always safe as long as
the sources have not changed underneath you).

Usage:
    python 01_merge_convert.py \
        --bits2bites  /work/grana_maxillo/lborghi/datasets/Bits2Bites \
        --bits2bites2 /work/grana_maxillo/lborghi/datasets/Bits2Bites2 \
        --output      /work/grana_maxillo/lborghi/datasets/Bits2Bites_merged \
        --force
"""
import argparse
import csv
import json
import shutil
import sys
from pathlib import Path

# Bits2Bites2 label `code` -> the English Annotations.csv vocabulary that
# prepare_bits2bites.py already knows how to translate into the training labels.
SAGITTAL_MAP = {
    "I": "Class I",
    "II_edge": "Class II Edge to Edge",
    "II_full": "Class II Full",
    "III": "Class III",
    "Unknown": "Unknown",
}
VERTICAL_MAP = {
    "normal": "Normal",
    "deep": "Deep Bite",
    "open": "Open Bite",
    "reverse": "Inverted Bite",
    "Unknown": "Unknown",
}
TRANSVERSE_MAP = {
    "normal": "Normal",
    "cross": "Cross Bite",
    "scissor": "Scissor Bite",
    "Unknown": "Unknown",
}
MIDLINE_MAP = {
    "deviated": "Deviated",
    "centered": "Centered",
    "Unknown": "Unknown",
}

CSV_HEADER = ["Patient", "Right Class", "Left Class", "Anterior Bite", "Transversal Bite", "Median Lines"]
REQUIRED_A_COLUMNS = set(CSV_HEADER)


def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--bits2bites", type=Path, required=True, help="Existing Bits2Bites dataset (A) — source of truth format")
    p.add_argument("--bits2bites2", type=Path, required=True, help="Raw Bits2Bites2 export (B) to normalize and append")
    p.add_argument("--output", type=Path, required=True, help="Where to write the merged raw-format dataset")
    p.add_argument("--force", action="store_true", help="Delete --output first if it already exists")
    return p.parse_args()


def _map_code(mapping: dict, block: dict, axis: str) -> str:
    """Look up one occlusion axis' code; unknown/missing -> 'Unknown' (=> ignored in training)."""
    entry = block.get(axis) or {}
    return mapping.get(entry.get("code"), "Unknown")


def _invalid_stl_reason(paths: list[Path]) -> str | None:
    """Return a report reason if any STL is missing or too small to be valid."""
    problems = []
    for path in paths:
        if not path.exists():
            problems.append(f"missing {path.name}")
            continue
        size = path.stat().st_size
        if size < 84:
            problems.append(f"invalid/empty {path.name} ({size} bytes)")
    return "; ".join(problems) if problems else None


def copy_bits2bites(src: Path, out: Path):
    """Copy A verbatim (patient folders + landmarks/) as the first N patients."""
    with open(src / "Annotations.csv", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        missing = REQUIRED_A_COLUMNS - set(reader.fieldnames or [])
        if missing:
            raise RuntimeError(f"{src / 'Annotations.csv'} missing columns: {sorted(missing)}")
        src_rows = list(reader)

    rows = []
    mapping = []
    for row in src_rows:
        pid = row["Patient"]
        shutil.copytree(src / pid, out / pid)
        contents = sorted(p.name for p in (out / pid).iterdir())
        if contents != ["lower.stl", "upper.stl"]:
            raise RuntimeError(f"{out / pid} unexpected contents: {contents}")
        # Read by column name, not position: some corrected A CSVs have Left before Right.
        rows.append([pid, row["Right Class"], row["Left Class"],
                     row["Anterior Bite"], row["Transversal Bite"], row["Median Lines"]])
        mapping.append([pid, "A", pid])

    landmarks_src = src / "landmarks"
    if landmarks_src.is_dir():
        shutil.copytree(landmarks_src, out / "landmarks")

    return rows, mapping


def convert_bits2bites2(src: Path, out: Path, next_id: int):
    """Append B patients with a manual label, renumbered from next_id."""
    folders = sorted(
        (p for p in src.iterdir() if p.is_dir()),
        key=lambda p: int(p.name.split("_")[1]),
    )

    rows, mapping, dropped = [], [], []
    for folder in folders:
        classification_path = folder / "bite_classification" / "classification.json"
        if not classification_path.is_file():
            dropped.append([folder.name, "", "missing classification.json"])
            continue

        data = json.loads(classification_path.read_text())
        orig_pid = data.get("patient_id", "")
        manual = data.get("manual")

        if manual is None:
            # Auto-generated pipeline label only — not expert-reviewed. Log by
            # original folder name so the doctor can find and re-annotate it.
            dropped.append([folder.name, orig_pid, "missing manual (expert) label"])
            continue

        raw_dir = folder / "ios" / "raw"
        lower_src = raw_dir / f"ios_lower_patient_{orig_pid}.stl"
        upper_src = raw_dir / f"ios_upper_patient_{orig_pid}.stl"
        invalid_reason = _invalid_stl_reason([lower_src, upper_src])
        if invalid_reason:
            dropped.append([folder.name, orig_pid, invalid_reason])
            continue

        new_id = next_id
        next_id += 1
        dst_folder = out / str(new_id)
        dst_folder.mkdir()
        shutil.copy2(lower_src, dst_folder / "lower.stl")
        shutil.copy2(upper_src, dst_folder / "upper.stl")

        # Photos kept aside for a future extension (all formats, incl .heic).
        photo_src = folder / "intraoral-photo" / "raw"
        if photo_src.is_dir():
            photo_dst = out / "photos" / str(new_id)
            photo_dst.mkdir(parents=True)
            for f in sorted(photo_src.iterdir()):
                if f.is_file():
                    shutil.copy2(f, photo_dst / f.name)

        rows.append([
            str(new_id),
            SAGITTAL_MAP.get(manual.get("sagittal_right", {}).get("code"), "Unknown"),
            SAGITTAL_MAP.get(manual.get("sagittal_left", {}).get("code"), "Unknown"),
            _map_code(VERTICAL_MAP, manual, "vertical"),
            _map_code(TRANSVERSE_MAP, manual, "transverse"),
            _map_code(MIDLINE_MAP, manual, "midline"),
        ])
        mapping.append([str(new_id), "B", folder.name])

    return rows, mapping, dropped


def write_csv(path: Path, header, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\r\n")
        writer.writerow(header)
        writer.writerows(rows)


def main():
    args = parse_args()

    if args.output.exists():
        if not args.force:
            print(f"error: {args.output} already exists (pass --force to overwrite)", file=sys.stderr)
            sys.exit(1)
        shutil.rmtree(args.output)
    args.output.mkdir(parents=True)

    a_rows, a_map = copy_bits2bites(args.bits2bites, args.output)
    next_id = len(a_rows) + 1

    b_rows, b_map, dropped = convert_bits2bites2(args.bits2bites2, args.output, next_id)

    write_csv(args.output / "Annotations.csv", CSV_HEADER, a_rows + b_rows)
    write_csv(args.output / "reports" / "id_mapping.csv",
              ["new_id", "source", "original_folder"], a_map + b_map)
    write_csv(args.output / "reports" / "dropped_no_manual.csv",
              ["original_folder", "patient_id", "reason"], dropped)

    total = len(a_rows) + len(b_rows)
    print(f"Wrote {total} patients to {args.output} "
          f"(1-{len(a_rows)} from Bits2Bites, {len(a_rows) + 1}-{total} from Bits2Bites2).")
    print(f"Dropped {len(dropped)} Bits2Bites2 patients -> reports/dropped_no_manual.csv")
    print(f"ID mapping (SENSITIVE, may contain real names) -> reports/id_mapping.csv")


if __name__ == "__main__":
    main()
